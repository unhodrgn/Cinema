"""Regenerate validation classes using Python Unicode 15.0 and DerivedCoreProperties.txt."""
import json
import sys
import unicodedata as u
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PUNCT = "_.+@-"
EMAIL = r"[A-Za-z0-9][A-Za-z0-9_+-]*([.][A-Za-z0-9_+-]+)*@[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?([.][A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)*[.][A-Za-z]([A-Za-z0-9-]*[A-Za-z0-9])?"


def spans(points):
    ranges = []
    for point in points:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return "".join(chr(start) if start == end else f"{chr(start)}-{chr(end)}" for start, end in ranges)


def main():
    data = Path(sys.argv[1]).read_text(encoding="utf8")
    assert data.startswith("# DerivedCoreProperties-15.0.0.txt")
    assert u.unidata_version == "15.0.0"
    ignored = set()
    for line in data.splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) != 2 or fields[1].strip() != "Default_Ignorable_Code_Point":
            continue
        bounds = fields[0].strip().split("..")
        ignored.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    allowed = []
    raw = []
    for point in range(sys.maxunicode + 1):
        ch = chr(point)
        category = u.category(ch)
        if point in ignored or category.startswith(("C", "Z")):
            continue
        if category.startswith("L") or category == "Nd":
            allowed.append(point)
        normalized = u.normalize("NFKC", ch)
        if all(
            ord(c) not in ignored and (c in PUNCT or u.category(c).startswith(("L", "M")) or u.category(c) == "Nd")
            for c in normalized
        ):
            raw.append(point)
    classes = {
        "RAW_CLASS": spans(p for p in raw if chr(p) not in PUNCT) + PUNCT,
        "LETTER_DIGIT": spans(allowed),
        "EMAIL": EMAIL,
    }
    header = "Generated by backend/scripts/generate_username_policy.py from Unicode 15.0.0."
    (ROOT / "backend/app/core/username_policy_data.py").write_text(
        f"# {header}\n" + "".join(f"{k} = {v!r}\n" for k,v in classes.items()), encoding="utf8"
    )
    (ROOT / "frontend/js/username-policy-data.js").write_text(
        f"// {header}\n" + "".join(f"export const {k} = {json.dumps(v, ensure_ascii=False)};\n" for k,v in classes.items()),
        encoding="utf8",
    )
    migration = ROOT / "backend/migrations/0006_username_validation.sql"
    before, _, tail = migration.read_text(encoding="utf8").partition("-- BEGIN GENERATED POLICY\n")
    _, marker, after = tail.partition("-- END GENERATED POLICY\n")
    assert marker
    generated = (
        f"    AND (value COLLATE \"C\" ~ $rx$^[{classes['LETTER_DIGIT']}][{classes['LETTER_DIGIT']}_.+-]*$$rx$\n"
        f"         OR value COLLATE \"C\" ~ $rx$^{EMAIL}$$rx$)\n"
    )
    migration.write_text(before + "-- BEGIN GENERATED POLICY\n" + generated + marker + after, encoding="utf8")


if __name__ == "__main__":
    main()
